#!/usr/bin/env bash
# Regenerates deploy/apache-cloudflare-only.conf from Cloudflare's published ranges.
# Usage: deploy/update-cloudflare-ips.sh   (then review the diff, commit, deploy, and reload Apache on the server)
set -euo pipefail
cd "$(dirname "$0")"
OUT=apache-cloudflare-only.conf
V4=$(curl -fsS https://www.cloudflare.com/ips-v4)
V6=$(curl -fsS https://www.cloudflare.com/ips-v6)
# refuse to write a list that looks wrong: a bad fetch must never produce an empty (lock-everyone-out) allow-list
[ "$(printf '%s\n' "$V4" | grep -cE '^[0-9.]+/[0-9]+$')" -ge 5 ] || { echo "unexpected IPv4 list, not writing" >&2; exit 1; }
[ "$(printf '%s\n' "$V6" | grep -cE '^[0-9a-f:]+/[0-9]+$')" -ge 3 ] || { echo "unexpected IPv6 list, not writing" >&2; exit 1; }
{
  echo "# Generated by deploy/update-cloudflare-ips.sh on $(date -u +%F). Do not edit by hand."
  echo "# Source: https://www.cloudflare.com/ips-v4 and /ips-v6. Only Cloudflare (and this machine) may reach the site,"
  echo "# so the client address the app derives from X-Forwarded-For cannot be spoofed by bypassing Cloudflare."
  echo "<Location />"
  echo "    <RequireAny>"
  echo "        Require ip 127.0.0.1 ::1"
  printf '%s\n' "$V4" "$V6" | sed 's/^/        Require ip /'
  echo "    </RequireAny>"
  echo "</Location>"
} > "$OUT.tmp"
mv "$OUT.tmp" "$OUT"
echo "wrote deploy/$OUT"
